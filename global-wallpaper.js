// Global wallpaper-symmetry layer for the kaleidoscope.
//
// This module is intentionally GROUP-THEORETIC rather than "tile-ish".
// Each wallpaper mode is defined by:
//
//   1. its translation lattice, and
//   2. a finite set of coset representatives for G / T,
//
// where G is the wallpaper group and T is its translation subgroup.
//
// For a global point p we:
//
//   p -> fractional lattice coordinates
//     -> quotient by translations (mod Z^2)
//     -> enumerate the finite G/T orbit
//     -> choose one deterministic canonical representative
//     -> convert that representative back to a local Cartesian coordinate
//
// That gives an actual quotient map R^2 -> R^2 / G. The existing local
// kaleidoscope motif in app.js is applied AFTER this global map.
//
// IMPORTANT CONSEQUENCE:
// If the local motif itself has extra symmetry, the rendered result can have a
// larger symmetry group than the selected wallpaper group. That is
// mathematically correct: imposing p3m1 on a motif that already identifies the
// extra p6m operations can make the two rendered results coincide.

export const GLOBAL_WALLPAPER_MODES = [
  "single",
  "p6m",
  "p6",
  "p4m",
  "p4g",
  "p3m1",
  "p3",

  // Added without disturbing the existing numeric indices 0..6.
  "p31m"
];

export const GLOBAL_WALLPAPER_LABELS = {
  single: "Single",
  p6m: "Hex Flower (p6m)",
  p6: "Hex Spin (p6)",
  p4m: "Crystal Grid (p4m)",
  p4g: "Interlock (p4g)",
  p3m1: "Tri Flower (p3m1)",
  p3: "Tri Spin (p3)",
  p31m: "Tri Mirror (p31m)"
};

export function globalWallpaperModeIndex(mode) {
  const index = GLOBAL_WALLPAPER_MODES.indexOf(mode);
  return index >= 0 ? index : 0;
}

// GLSL injected into the main fragment shader.
//
// Coordinate contract:
//   input p = global canvas-space point, already aspect-corrected
//   output  = canonical local coordinate for the selected wallpaper group
//
// Mode numbering intentionally preserves the first implementation:
//
//   0 single
//   1 p6m
//   2 p6
//   3 p4m
//   4 p4g
//   5 p3m1
//   6 p3
//   7 p31m
//
// Generator conventions
// ---------------------
//
// Square lattice basis:
//
//   e1 = (1,0)
//   e2 = (0,1)
//
//   R4 = [[ 0,-1],
//         [ 1, 0]]
//
//   Mx = [[1, 0],
//         [0,-1]]
//
// p4m is generated by R4 and (Mx, 0).
// p4g is generated by R4 and (Mx, 1/2(e1+e2)).
//
// Hexagonal lattice basis:
//
//   t1 = (1,0)
//   t2 = (-1/2, sqrt(3)/2)
//
// In fractional (t1,t2) coordinates:
//
//   R3      = [[0,-1],
//              [1,-1]]
//
//   R6      = [[1,-1],
//              [1, 0]]
//
//   M6      = [[1,-1],
//              [0,-1]]
//
//   M3long  = [[1, 0],
//              [1,-1]]   -> p3m1
//
//   M3short = [[1,-1],
//              [0,-1]]   -> p31m
//
// These are crystallographic generators for the corresponding point groups
// acting on the square / hexagonal translation lattices.

export const GLOBAL_WALLPAPER_GLSL = String.raw`
const float WALLPAPER_SQRT3 = 1.7320508075688772935;
const float WALLPAPER_SQRT3_OVER_2 = 0.86602540378443864676;
const float WALLPAPER_EPS = 0.000001;


// ===========================================================================
// Numerically stable torus helpers
// ===========================================================================

float wallpaperWrap01Scalar(float x) {
  float y = fract(x);

  // Different group words can land numerically on 0.0 or 0.99999994 at a
  // lattice boundary. Snap both representations to the same torus point.
  if (y < WALLPAPER_EPS || y > 1.0 - WALLPAPER_EPS) {
    return 0.0;
  }

  return y;
}


vec2 wallpaperWrap01(vec2 p) {
  return vec2(
    wallpaperWrap01Scalar(p.x),
    wallpaperWrap01Scalar(p.y)
  );
}


vec2 wallpaperCentered(vec2 p) {
  // Canonical fractional coordinate -> nearest translated representative
  // around the lattice origin.
  //
  // Equality on the torus is preserved.

  vec2 q = fract(p + 0.5) - 0.5;

  if (abs(q.x) < WALLPAPER_EPS) {
    q.x = 0.0;
  }

  if (abs(q.y) < WALLPAPER_EPS) {
    q.y = 0.0;
  }

  return q;
}


bool wallpaperLexLess(vec2 candidate, vec2 best) {
  if (candidate.x < best.x - WALLPAPER_EPS) {
    return true;
  }

  if (
    abs(candidate.x - best.x) <= WALLPAPER_EPS &&
    candidate.y < best.y - WALLPAPER_EPS
  ) {
    return true;
  }

  return false;
}


vec2 wallpaperChooseCanonical(vec2 best, vec2 candidate) {
  candidate = wallpaperWrap01(candidate);

  return wallpaperLexLess(candidate, best)
    ? candidate
    : best;
}


// ===========================================================================
// Square lattice
// ===========================================================================

vec2 wallpaperSquareToFractional(vec2 p, float spacing) {
  return p / spacing;
}


vec2 wallpaperSquareFromFractional(vec2 f, float spacing) {
  return f * spacing;
}


vec2 wallpaperSquareR4(vec2 f) {
  // [[0,-1],
  //  [1, 0]] f

  return vec2(
    -f.y,
     f.x
  );
}


vec2 wallpaperSquareMirrorX(vec2 f) {
  // [[1, 0],
  //  [0,-1]] f

  return vec2(
     f.x,
    -f.y
  );
}


vec2 wallpaperSquareP4GGlide(vec2 f) {
  // (Mx, 1/2(e1+e2)) f
  //
  // This is a genuine affine coset representative rather than an
  // alternating-cell approximation.
  //
  // Combined with R4 it generates p4g.

  return vec2(
     f.x + 0.5,
    -f.y + 0.5
  );
}


vec2 wallpaperCanonicalP4M(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // D4:
  //
  // { R4^k, Mx R4^k | k = 0..3 }

  for (int k = 0; k < 4; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    best = wallpaperChooseCanonical(
      best,
      wallpaperSquareMirrorX(r)
    );

    r = wallpaperSquareR4(r);
  }

  return best;
}


vec2 wallpaperCanonicalP4G(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // G/T has the same D4 point group as p4m, but the
  // orientation-reversing coset is affine.
  //
  // Representatives:
  //
  // { R4^k, S R4^k }
  //
  // where
  //
  // S = (Mx, 1/2(e1+e2))

  for (int k = 0; k < 4; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    best = wallpaperChooseCanonical(
      best,
      wallpaperSquareP4GGlide(r)
    );

    r = wallpaperSquareR4(r);
  }

  return best;
}


// ===========================================================================
// Hexagonal / triangular lattice
// ===========================================================================
//
// Basis:
//
//   t1 = (1, 0)
//   t2 = (-1/2, sqrt(3)/2)
//
// This uses the -1/2 convention because the integer matrices below are written
// in this crystallographic basis.

vec2 wallpaperHexToFractional(vec2 p, float spacing) {
  // p / spacing = x*t1 + y*t2
  //
  // Cartesian:
  //
  // X = x - y/2
  // Y = sqrt(3)/2 * y

  float y =
    p.y /
    (WALLPAPER_SQRT3_OVER_2 * spacing);

  float x =
    p.x / spacing +
    0.5 * y;

  return vec2(x, y);
}


vec2 wallpaperHexFromFractional(vec2 f, float spacing) {
  return spacing * vec2(
    f.x - 0.5 * f.y,
    WALLPAPER_SQRT3_OVER_2 * f.y
  );
}


// ---------------------------------------------------------------------------
// Hexagonal point-group generators
// ---------------------------------------------------------------------------

vec2 wallpaperHexR3(vec2 f) {
  // [[0,-1],
  //  [1,-1]] f
  //
  // 120-degree rotation.

  return vec2(
    -f.y,
     f.x - f.y
  );
}


vec2 wallpaperHexR6(vec2 f) {
  // [[1,-1],
  //  [1, 0]] f
  //
  // 60-degree rotation.

  return vec2(
    f.x - f.y,
    f.x
  );
}


vec2 wallpaperHexM6(vec2 f) {
  // [[1,-1],
  //  [0,-1]] f
  //
  // Reflection fixing the t1 axis.
  //
  // Together with R6:
  //
  // D6 -> p6m

  return vec2(
     f.x - f.y,
    -f.y
  );
}


vec2 wallpaperHexM3Long(vec2 f) {
  // [[1, 0],
  //  [1,-1]] f
  //
  // D3 "long-diagonal" embedding.
  //
  // Together with R3:
  //
  // p3m1

  return vec2(
    f.x,
    f.x - f.y
  );
}


vec2 wallpaperHexM3Short(vec2 f) {
  // [[1,-1],
  //  [0,-1]] f
  //
  // D3 "short-diagonal" embedding.
  //
  // Together with R3:
  //
  // p31m

  return vec2(
     f.x - f.y,
    -f.y
  );
}


// ===========================================================================
// p6
// ===========================================================================

vec2 wallpaperCanonicalP6(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // C6:
  //
  // { R6^k | k = 0..5 }

  for (int k = 0; k < 6; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    r = wallpaperHexR6(r);
  }

  return best;
}


// ===========================================================================
// p6m
// ===========================================================================

vec2 wallpaperCanonicalP6M(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // D6:
  //
  // { R6^k, M6 R6^k | k = 0..5 }

  for (int k = 0; k < 6; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    best = wallpaperChooseCanonical(
      best,
      wallpaperHexM6(r)
    );

    r = wallpaperHexR6(r);
  }

  return best;
}


// ===========================================================================
// p3
// ===========================================================================

vec2 wallpaperCanonicalP3(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // C3:
  //
  // { I, R3, R3^2 }

  for (int k = 0; k < 3; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    r = wallpaperHexR3(r);
  }

  return best;
}


// ===========================================================================
// p3m1
// ===========================================================================

vec2 wallpaperCanonicalP3M1(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // D3,long:
  //
  // { R3^k, M3long R3^k | k = 0..2 }
  //
  // All 3-fold centres lie on reflection axes in p3m1.

  for (int k = 0; k < 3; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    best = wallpaperChooseCanonical(
      best,
      wallpaperHexM3Long(r)
    );

    r = wallpaperHexR3(r);
  }

  return best;
}


// ===========================================================================
// p31m
// ===========================================================================

vec2 wallpaperCanonicalP31M(vec2 f) {
  f = wallpaperWrap01(f);

  vec2 best = f;
  vec2 r = f;

  // D3,short:
  //
  // { R3^k, M3short R3^k | k = 0..2 }
  //
  // Unlike p3m1, p31m has 3-fold centres that lie off mirror lines.

  for (int k = 0; k < 3; ++k) {
    best = wallpaperChooseCanonical(
      best,
      r
    );

    best = wallpaperChooseCanonical(
      best,
      wallpaperHexM3Short(r)
    );

    r = wallpaperHexR3(r);
  }

  return best;
}


// ===========================================================================
// Public global quotient map
// ===========================================================================

vec2 globalWallpaperPoint(
  vec2 p,
  int mode,
  float patternSize
) {
  if (mode == 0) {
    return p;
  }

  float spacing =
    max(patternSize, 0.02);


  // -------------------------------------------------------------------------
  // Hexagonal-lattice groups
  // -------------------------------------------------------------------------

  if (
    mode == 1 ||
    mode == 2 ||
    mode == 5 ||
    mode == 6 ||
    mode == 7
  ) {
    vec2 f =
      wallpaperHexToFractional(
        p,
        spacing
      );

    vec2 canonical =
      wallpaperWrap01(f);

    if (mode == 1) {
      canonical =
        wallpaperCanonicalP6M(f);
    }

    if (mode == 2) {
      canonical =
        wallpaperCanonicalP6(f);
    }

    if (mode == 5) {
      canonical =
        wallpaperCanonicalP3M1(f);
    }

    if (mode == 6) {
      canonical =
        wallpaperCanonicalP3(f);
    }

    if (mode == 7) {
      canonical =
        wallpaperCanonicalP31M(f);
    }

    return wallpaperHexFromFractional(
      wallpaperCentered(canonical),
      spacing
    );
  }


  // -------------------------------------------------------------------------
  // Square-lattice groups
  // -------------------------------------------------------------------------

  if (
    mode == 3 ||
    mode == 4
  ) {
    vec2 f =
      wallpaperSquareToFractional(
        p,
        spacing
      );

    vec2 canonical =
      mode == 3
        ? wallpaperCanonicalP4M(f)
        : wallpaperCanonicalP4G(f);

    return wallpaperSquareFromFractional(
      wallpaperCentered(canonical),
      spacing
    );
  }


  return p;
}
`;
